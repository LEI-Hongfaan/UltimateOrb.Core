        readonly ref struct UnsafeUInt128Accessor {

            readonly ref readonly UInt64 @base;

            public UnsafeUInt128Accessor(in UInt64 @base) {
                this.@base = ref @base;
            }

            public UInt128 this[uint index] {

                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                get {
                    // Flat table layout is [lo, hi] per UInt128 (little-endian).
                    // U128(hi, lo) therefore wants the limb at +8 first, the limb at +0 second.
                    return U128(
                        Unsafe.AddByteOffset(ref Unsafe.AsRef(in @base), unchecked((uint)sizeof(UInt64) + (uint)sizeof(UInt128) * index)),
                        Unsafe.AddByteOffset(ref Unsafe.AsRef(in @base), unchecked((uint)sizeof(UInt128) * index)));
                }
            }
        }

