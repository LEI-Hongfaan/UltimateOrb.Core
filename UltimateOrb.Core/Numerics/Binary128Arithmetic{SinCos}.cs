        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static InlineArray3<TUInt> AddUnchecked<TUInt>(in InlineArray3<TUInt> a, in InlineArray3<TUInt> b)
            where TUInt : IAdditionOperators<TUInt, TUInt, TUInt>?, IComparisonOperators<TUInt, TUInt, bool>?, IUnsignedNumber<TUInt>? {
            unchecked {
                Debug.Assert(TUInt.CreateTruncating(2) == checked(TUInt.One + TUInt.One));
                InlineArray3<TUInt> r = default;
                var c0 = AddNoThrow(a[0], b[0], out r[0]);
                var c1 = AddNoThrow(a[1], b[1], out r[1]);
                var c2 = AddNoThrow(r[1], TUInt.CreateTruncating(c0), out r[1]);
                r[2] = a[2] + b[2] + TUInt.CreateTruncating(c1 + c2);
                return r;
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static InlineArray3<TUInt> SubtractUnchecked<TUInt>(in InlineArray3<TUInt> a, in InlineArray3<TUInt> b)
            where TUInt : ISubtractionOperators<TUInt, TUInt, TUInt>?, IComparisonOperators<TUInt, TUInt, bool>?, IUnsignedNumber<TUInt>? {
            unchecked {
                Debug.Assert(TUInt.CreateTruncating(2) == checked(TUInt.One + TUInt.One));
                InlineArray3<TUInt> r = default;
                var c0 = SubtractNoThrow(a[0], b[0], out r[0]);
                var c1 = SubtractNoThrow(a[1], b[1], out r[1]);
                var c2 = SubtractNoThrow(r[1], TUInt.CreateTruncating(c0), out r[1]);
                r[2] = a[2] - b[2] - TUInt.CreateTruncating(c1 + c2);
                return r;
            }
        }

        // x << shift, discarding whatever leaves the window, for shift < 384
        // ~Core: shift amount must be normalized.
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static InlineArray3<TUInt> ShiftLeftCore<TUInt>(in InlineArray3<TUInt> x, int shift)
            where TUInt : IShiftOperators<TUInt, int, TUInt>?, IUnsignedNumber<TUInt>?, IBinaryInteger<TUInt>, IMinMaxValue<TUInt>? {
            Debug.Assert(0 <= shift);
            Debug.Assert(shift < checked(3 * IntTypeTraits<TUInt>.BitWidth));
            unchecked {
                uint word = shift.ToUnsignedUnchecked() / IntTypeTraits<TUInt>.BitWidth.ToUnsignedUnchecked();
                uint bits = shift.ToUnsignedUnchecked() % IntTypeTraits<TUInt>.BitWidth.ToUnsignedUnchecked();
                InlineArray3<TUInt> r = default;
                for (uint i = word; i < 3; i++) {
                    TUInt carry = (bits == 0 || i == word) ? TUInt.Zero : x[(int)(i - word - 1)] >> (128 - (int)bits);
                    r[(int)i] = (x[(int)(i - word)] << (int)bits) | carry;
                }
                return r;
            }
        }

        // x >> shift, saturating to zero past the window
        // ~Full: handles full ranged shift amount
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static InlineArray3<TUInt> ShiftRightUnsignedFull<TUInt>(in InlineArray3<TUInt> x, int shift)
            where TUInt : IShiftOperators<TUInt, int, TUInt>?, IUnsignedNumber<TUInt>?, IBinaryInteger<TUInt>, IMinMaxValue<TUInt>? {
            unchecked {
                InlineArray3<TUInt> r = default;
                if (shift >= checked(3 * IntTypeTraits<TUInt>.BitWidth)) return default;
                uint word = shift.ToUnsignedUnchecked() / IntTypeTraits<TUInt>.BitWidth.ToUnsignedUnchecked();
                uint bits = shift.ToUnsignedUnchecked() % IntTypeTraits<TUInt>.BitWidth.ToUnsignedUnchecked();
                for (uint i = word; i < 3; i++) {
                    TUInt carry = (i + 1 < 3 && bits != 0) ? x[(int)(i + 1)] << (IntTypeTraits<TUInt>.BitWidth - (int)bits) : TUInt.Zero;
                    r[(int)(i - word)] = (x[(int)i] >> (int)bits) | carry;
                }
                return r;
            }
        }

        // leading zeros of a 384-bit value, 384 when it is zero
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static int LeadingZeroCount<TUInt>(in InlineArray3<TUInt> x)
            where TUInt : IUnsignedNumber<TUInt>?, IBinaryInteger<TUInt>, IMinMaxValue<TUInt>? {
            unchecked {
                if (!TUInt.IsZero(x[2])) return int.CreateTruncating(TUInt.LeadingZeroCount(x[2]));
                if (!TUInt.IsZero(x[1])) return IntTypeTraits<TUInt>.BitWidth + int.CreateTruncating(TUInt.LeadingZeroCount(x[1]));
                return checked(2 * IntTypeTraits<TUInt>.BitWidth) + int.CreateTruncating(TUInt.LeadingZeroCount(x[0]));
            }
        }

        /* high 384 bits of a 384x384-bit product: the dropped tail leaves it up to
           four units short of the exact value, never over */

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static InlineArray3<TUInt> MultiplyHighUnsignedApproximate<TUInt>(InlineArray3<TUInt> a, InlineArray3<TUInt> b)
            where TUInt : IUnsignedNumber<TUInt>?, IBinaryInteger<TUInt>, IMinMaxValue<TUInt>? {
            Debug.Assert(TUInt.CreateTruncating(3) == checked(TUInt.One + TUInt.One + TUInt.One));
            unchecked {
                TUInt h02, l02, h11, l11, h20, l20, h12, l12, h21, l21, h22, l22, sum, diagonal;
                StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out l02, out h02, a[0], b[2]);
                StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out l02, out h02, a[0], b[2]);
                StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out l11, out h11, a[1], b[1]);
                StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out l20, out h20, a[2], b[0]);
                StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out l12, out h12, a[1], b[2]);
                StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out l21, out h21, a[2], b[1]);
                StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out l22, out h22, a[2], b[2]);
                /* The diagonal one limb below the window contributes its high halves plus
                   the carry of its low halves; everything further down is the slack above. */
                var carry_low = AddNoThrow(l02, l11, out sum);
                var carry_high = AddNoThrow(sum, l20, out sum);
                var first = AddNoThrow(h02, h11, out diagonal);
                var second = AddNoThrow(diagonal, h20, out diagonal);
                var third = AddNoThrow(diagonal, TUInt.CreateTruncating(carry_low + carry_high), out diagonal);
                InlineArray3<TUInt> t1 = default;
                t1[0] = l12;
                t1[1] = h12;
                t1[2] = TUInt.Zero;

                InlineArray3<TUInt> t2 = default;
                t2[0] = l21;
                t2[1] = h21;
                t2[2] = TUInt.Zero;

                InlineArray3<TUInt> t3 = default;
                t3[0] = TUInt.Zero;
                t3[1] = l22;
                t3[2] = h22;

                InlineArray3<TUInt> t4 = default;
                t4[0] = diagonal;
                t4[1] = TUInt.CreateTruncating(first + second + third);
                t4[2] = TUInt.Zero;

                return AddUnchecked(AddUnchecked(t1, t2), AddUnchecked(t3, t4));
            }

        }
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static void BigMul<TUInt>(out InlineArray2<TUInt> result, TUInt a, TUInt b)
            where TUInt : IUnsignedNumber<TUInt>?, IBinaryInteger<TUInt>, IMinMaxValue<TUInt>? {
            Unsafe.SkipInit(out result);
            StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out result[0], out result[1], a, b);
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static TUInt MultiplyHighUnsignedApproximate<TUInt>(TUInt x, TUInt y)
            where TUInt : IUnsignedNumber<TUInt>?, IBinaryInteger<TUInt>, IMinMaxValue<TUInt>? {
            unchecked {
                if (typeof(TUInt) == typeof(uint)) {
                    return (TUInt)(object)(uint)(((ulong)(uint)(object)x * (uint)(object)y) >> IntTypeTraits<uint>.BitWidth);
                } else if (typeof(TUInt) == typeof(nuint)) {
                    if (nuint.Size == sizeof(uint)) {
                        return (TUInt)(object)(nuint)MultiplyHighUnsignedApproximate<uint>((uint)(nuint)(object)x, (uint)(nuint)(object)y);
                    } else if (nuint.Size == sizeof(ulong)) {
                        return (TUInt)(object)(nuint)MultiplyHighUnsignedApproximate<ulong>((ulong)(nuint)(object)x, (ulong)(nuint)(object)y);
                    }
                } else if (typeof(TUInt) == typeof(ulong)) {
                    return (TUInt)(object)(ulong)(((System.UInt128)(ulong)(object)x * (ulong)(object)y) >> IntTypeTraits<ulong>.BitWidth);
                } else if (typeof(TUInt) == typeof(System.UInt128)) {
                    return (TUInt)(object)(System.UInt128)MultiplyHighApproximate((System.UInt128)(object)x, (System.UInt128)(object)y);
                } else if (typeof(TUInt) == typeof(UltimateOrb.UInt128)) {
                    return (TUInt)(object)(UltimateOrb.UInt128)MultiplyHighApproximate((UltimateOrb.UInt128)(object)x, (UltimateOrb.UInt128)(object)y);
                }
                {
                    var halfBitWidth = checked(IntTypeTraits<TUInt>.BitWidth + 1) / 2;
                    var mask = TUInt.AllBitsSet >>> (IntTypeTraits<TUInt>.BitWidth - halfBitWidth);
                    TUInt xh = x >> halfBitWidth, xl = mask & x, yh = y >> halfBitWidth, yl = mask & y;
                    return xh * yh + ((xh * yl) >> halfBitWidth) + ((xl * yh) >> halfBitWidth);
                }
            }
        }

        /* high 256 bits of a 256x256-bit product: the dropped tail leaves it up to
           one unit short of the exact value, never over */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static InlineArray2<TUInt> MultiplyHighUnsignedApproximate<TUInt>(InlineArray2<TUInt> a, InlineArray2<TUInt> b)
            where TUInt : IUnsignedNumber<TUInt>?, IBinaryInteger<TUInt>, IMinMaxValue<TUInt>? {
            Debug.Assert(TUInt.CreateTruncating(4) == checked(TUInt.One + TUInt.One + TUInt.One + TUInt.One));
            unchecked {

                TUInt high, low, cross_high, cross_low, other_high, other_low, sum, middle;
                StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out low, out high, a[1], b[1]);
                StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out cross_low, out cross_high, a[1], b[0]);
                StandardGenericMathArithmeticProvider<TUInt>.BigMulUnsigned(out other_low, out other_high, a[0], b[1]);
                /* The two cross terms and the top of a[0]*b[0] all land one limb below the
                   window, so only their carry into it survives. */
                var carry = AddNoThrow(cross_low, other_low, out sum);
                var tail_carry = AddNoThrow(sum, MultiplyHighUnsignedApproximate(a[0], b[0]), out sum);
                var overflow = AddNoThrow(cross_high, other_high, out middle);
                var spill = AddNoThrow(middle, TUInt.CreateTruncating(carry + tail_carry), out middle);
                var final_carry = AddNoThrow(low, middle, out low);
                InlineArray2<TUInt> r = default;
                r[0] = low;
                r[1] = high + TUInt.CreateTruncating(overflow + spill + final_carry);
                return r;
            }
        }

        /* ---------- reduction ---------- */

        /* m*win as W+3 little-endian 64-bit limbs, for a window win of W limbs most
           significant first: the product fills W+2 of them and the spare top limb
           stays zero so the funnels' last read is in range. */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        unsafe static void product(UInt128 m, ref readonly UInt64 win, int W, ref UInt64 p) {
            unchecked {
                UInt128 low = (UInt64)m, high = m >> 64, carry = 0;
                for (int c = 0; c < W + 3; c++) {
                    UInt128 cur = c < W ? Unsafe.Add(ref Unsafe.AsRef(in win), W - 1 - c) : 0;
                    UInt128 prev = (c >= 1 && c <= W) ? Unsafe.Add(ref Unsafe.AsRef(in win), W - c) : 0;
                    /* high < 2^49 keeps the first sum under 2^114; only the second can
                       spill, and its bit goes straight into the carry. */
                    UInt128 acc = high * prev + carry, t;
                    var spill = AddNoThrow(acc, low * cur, out t);
                    Unsafe.Add(ref p, c) = (UInt64)t;
                    carry = (t >> 64) | ((UInt128)spill << 64);
                }
            }
        }

        /* The 2/pi window and the product's alignment for x = m*2^(e-112): bits of
           2/pi above position e-114 contribute multiples of 4 to x*2/pi, so the
           window starts at the limb holding bit e-113; within it, *shift says how
           far the units bit of x*2/pi sits below the product's bit 64*W-2 --
           subtract below |x| = 2^114, where the window is the top of 2/pi. */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        unsafe static ref readonly UInt64 window(int e, out int shift) {
            unchecked {
                int big = e - 114;
                if (big >= 0) {
                    shift = (int)((uint)big % 64);
                    return ref Unsafe.Add(ref MemoryMarshal.GetReference(FRAC_2_PI), (uint)big / 64);
                }
                shift = big;
                return ref MemoryMarshal.GetReference(FRAC_2_PI);
            }
        }

        // the reduced angle theta = |g|*pi/2 as t1*2^(et-128), and its breakpoint
        [StructLayout(LayoutKind.Auto)]
        struct residual {
            public int n;        // round(256*x/pi) mod 512: quadrant n>>7, breakpoint n&127
            public int negative; // g < 0: the angle sits below its breakpoint
            public UInt128 t1;
            public int et;
        }

        /* Payne-Hanek on six limbs of 2/pi; 0 when the residual keeps fewer than
           136 of the fraction's 192 bits.  Five limbs would leave the tail of 2/pi
           below the window at 2^(shift-205) of the units bit, up to 2^-142, which
           the sine near a multiple of pi cannot afford; six put it under 2^-206. */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static int reduce(UInt128 m, int e, out residual r) {
            unchecked {
                ref readonly UInt64 win = ref window(e, out var shift);
                Span<UInt64> p = stackalloc UInt64[9];
                product(m, in win, 6, ref p[0]);
                /* The fraction is the 192 bits below the units bit, the quadrant the two
                   above: four funnels at one offset, from limb i <= 4. */
                var @base = 190u - shift.ToUnsignedUnchecked(); // 127 <= base <= 312
                var i = ((@base / 64) & 7).ToSignedUnchecked();
                var bits = (@base % 64).ToSignedUnchecked();
                UInt64 f0 = ShiftRightPartial(p[i], p[i + 1], bits);
                UInt64 f1 = ShiftRightPartial(p[i + 1], p[i + 2], bits);
                UInt64 f2 = ShiftRightPartial(p[i + 2], p[i + 3], bits);
                UInt64 quadrant = ShiftRightPartial(p[i + 3], p[i + 4], bits) & 3;

                // n = round(256*x/pi); the residual's top limb becomes signed
                UInt128 top = ((UInt128)quadrant << 64) | f2;
                int n = (int)(((top + ((UInt128)1 << 56)) >> 57) & 511);
                f2 -= (UInt64)(n & 127) << 57;
                var negative = (Int64)f2 < 0 ? 1 : 0;
                UInt64 mask = 0u - (UInt64)negative, g0, g1, g2;
                var c0 = AddNoThrow(f0 ^ mask, (UInt64)negative, out g0);
                var c1 = AddNoThrow(f1 ^ mask, (UInt64)c0, out g1);
                g2 = (f2 ^ mask) + c1;
                if (g2 == 0) {
                    r = default;
                    return 0;
                }
                int lz = (int)UInt64.LeadingZeroCount(g2);
                if (lz > MAX_LZ) {
                    r = default;
                    return 0;
                }
                /* |g| <= 1/256 leaves at least seven leading zeros, so every shift below
                   is in range; |g| = G*2^(-128-lz) for the top 128 bits G. */
                UInt64 high = (g2 << lz) | (g1 >> (64 - lz));
                UInt64 low = (g1 << lz) | (g0 >> (64 - lz));
                UInt128 g = ((UInt128)high << 64) | low, ph, pl;
                StandardGenericMathArithmeticProvider<UInt128>.BigMulUnsigned(out pl, out ph, g, PIO2_128);
                int lzt = LeadingZeroCount(ph);
                U256 t = default;
                t[0] = pl;
                t[1] = ph;
                {
                    residual residual = default;
                    residual.n = n;
                    residual.negative = negative;
                    residual.t1 = ShiftLeftHighPartial(t, lzt);
                    residual.et = 1 - (lz + lzt);
                    r = residual;
                }
                return 1;
            }
        }

        /* theta^2 rounded into a 2^-128 word (u), theta^4 likewise (v), and the
           unshifted theta^2 = u1*2^(2*et-128) the cosine's correction rides on */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static void squares(UInt128 t1, int et, out UInt128 u, out UInt128 v, out UInt128 u1) {
            var u1_ = MultiplyHighApproximate(t1, t1);
            var u_ = ShiftRightUnsignedRoundToNearestWithMidpointAwayFromZero(u1_, unchecked(-2 * et));
            var v_ = MultiplyHighApproximate(u_, u_);
            u1 = u1_;
            u = u_;
            v = v_;
        }

        /* sin(theta) in theta's own floating form: t1*(1 - u*(A - u*B)) with the
           even and odd halves of the degree-four minimax SIN_FAST in v.
           Its contribution to the ratio is below u*2^-114 < 2^-128.69. */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static UInt128 sin_frac(UInt128 t1, UInt128 u, UInt128 v) {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            static UInt128 S(uint indnx) {
                return SIN_FAST[indnx];
            }
            unchecked {
                UInt128 a = S(0) + MultiplyHighApproximate(v, S(2) + MultiplyHighApproximate(v, S(4)));
                UInt128 b = S(1) + MultiplyHighApproximate(v, S(3));
                return t1 - MultiplyHighApproximate(MultiplyHighApproximate(t1, u), a - MultiplyHighApproximate(u, b));
            }
        }

        /* 1 - cos(theta) as the floating fraction c1*2^(2*et-128): theta^2*(1/2 -
           u*W) with W the even and odd halves of sum (-1)^k u^k/(2k+4)! in v. Six
           terms: the omitted seventh contributes less than 2^-139 to cos(theta). */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static UInt128 cos_corr(UInt128 u1, UInt128 u, UInt128 v) {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            static UInt128 C(nuint k) {
                return COS_COEF[k, 2];
            }
            unchecked {
                UInt128 e = C(1) + MultiplyHighApproximate(v, C(3) + MultiplyHighApproximate(v, C(5)));
                UInt128 o = C(2) + MultiplyHighApproximate(v, C(4));
                return MultiplyHighApproximate(u1, C(0) - MultiplyHighApproximate(u, e - MultiplyHighApproximate(u, o)));
            }
        }


        // TODO(AI): Continue port the C/C++ code to modern C# 15+ and .NET 14+.
        /* The fast path: the magnitude as a floating 128-bit fraction frac*2^(e2-128)
   with the sign it contributes in *flip, or 0 when the reduction cannot
   vouch for it. */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static int fast(UInt128 m, int e, nint/*bool*/ cosine, out UInt128 frac, out int e2, out UInt128 flip) {
            unchecked {
                UInt128 u, v, u1;
                if (e < DIRECT) {
                    UInt128 t1 = m << 15;
                    int et = e + 1;
                    squares(t1, et, out u, out v, out u1);
                    if (0 != cosine) {
                        U256 all = default;
                        all[0] = ~(UInt128)0;
                        all[1] = ~(UInt128)0;
                        frac = SubtractUnchecked(all, BigShiftLeft(cos_corr(u1, u, v), 2 * et + 128))[1];
                        e2 = 0;
                    } else {
                        // sin(theta) < theta drops a leading bit when t1 starts a binade
                        UInt128 s1 = sin_frac(t1, u, v);
                        int lz = LeadingZeroCount(s1);
                        frac = s1 << lz;
                        e2 = et - lz;
                    }
                    flip = 0;
                    return 1;
                }
                {
                    residual r;
                    if (0 == reduce(m, e, out r)) {
                        frac = default;
                        e2 = default;
                        flip = default;
                        return 0;
                    }
                    squares(r.t1, r.et, out u, out v, out u1);
                    UInt128 s1 = sin_frac(r.t1, u, v);
                    /* The cosine is the sine a quadrant on; the top bit of the quadrant is the
                       sign, the low bit which of sin A and cos A is wanted. */
                    int k = (r.n >> 7) + (int)cosine, want_cos = k & 1, j = r.n & 127;
                    var flip_ = 0 != (k & 2) ? SIGN_MASK : 0;
                    if (j == 0 && 0 == want_cos) {
                        int lz = LeadingZeroCount(s1);
                        flip_ ^= 0 != r.negative ? SIGN_MASK : 0;
                        flip = flip_;
                        frac = s1 << lz;
                        e2 = r.et - lz;
                        return 1;
                    }
                    {
                        UInt128 c1 = cos_corr(u1, u, v);
                        var first = SINCOS[(uint)j, (uint)want_cos];
                        var second = SINCOS[(uint)j, 1 ^ (uint)want_cos];
                        U256 @base = default;
                        @base[0] = first[1];
                        @base[1] = first[2];
                        ;
                        U256 c = BigShiftLeft(MultiplyHighApproximate(first[2], c1), 2 * r.et + 128);
                        U256 s = BigShiftLeft(MultiplyHighApproximate(second[2], s1), r.et + 128);
                        U256 f = AddOrSubtractUnchecked(SubtractUnchecked(@base, c), s, r.negative != want_cos ? 1 : 0);
                        int lz = LeadingZeroCount(f[1]);
                        flip = flip_;
                        frac = ShiftLeftHighPartial(f, lz);
                        e2 = -lz;
                        return 1;
                    }
                }
            }
        }


        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static bool IsNearest(MidpointRounding mode) {
            return mode == MidpointRounding.ToEven || mode == MidpointRounding.AwayFromZero;
        }

        /* Round the fast frame on its fixed 15-bit guard; 0 hands the window around
           the rounding boundary to the accurate path.  The result is never subnormal
           here: |x| >= 2^-57 keeps it above 2^-124. */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static int round_fast(UInt128 frac, int e2, UInt128 sign, MidpointRounding rm, out UInt128 @out) {
            unchecked {
                uint rest = (uint)frac & GUARD_MASK;
                // the boundary is the midpoint in round-to-nearest, the grid point otherwise
                uint boundary = (IsNearest(rm) ? 1u : 0u) << (GUARD - 1);
                if (((rest + ZIV_GATE - boundary) & GUARD_MASK) <= 2 * ZIV_GATE) {
                    @out = default;
                    return 0;
                }
                /* The gate has already ruled out the boundary: the guard's top bit decides
                   in round-to-nearest, and the discarded bits cannot flip it; a directed
                   mode rounds the truncated frame by its direction alone. */
                int up = IsNearest(rm) ? (rest > GUARD_HALF ? 1 : 0) : round_away(rm, sign);
                @out = sign | (((UInt128)(e2 + 16382) << 112) + (frac >> GUARD) - IMPLICIT_BIT + (uint)up);
                return 1;
            }
        }

        /* ---------- the 384-bit path ---------- */

        // reduce() on ten limbs of 2/pi and a 448-bit fraction, the residual as a
        // normalized 384-bit fraction t*2^(et-384)
        static void reduce_wide(UInt128 m, int e, out int n, out nint/*bool*/ negative, out U384 t, out int et) {
            unchecked {
                int shift;
                ref readonly UInt64 win = ref window(e, out shift);
                Span<UInt64> p = stackalloc UInt64[13];
                product(m, in win, 10, ref p[0]);
                uint @base = 190 - shift.ToUnsignedUnchecked(); // 127 <= base <= 312
                uint i = (@base / 64) & 7, bits = @base % 64;
                Span<UInt64> f = stackalloc UInt64[7];
                for (int k = 0; k < 7; k++) f[k] = ShiftRightPartial(p[(int)i + k], p[(int)i + k + 1], (int)bits);
                UInt64 quadrant = ShiftRightPartial(p[(int)i + 7], p[(int)i + 8], (int)bits) & 3;
                UInt128 top = ((UInt128)quadrant << 64) | f[6];
                int nn = (int)(((top + ((UInt128)1 << 56)) >> 57) & 511);
                f[6] -= (UInt64)(nn & 127) << 57;
                nint neg = (Int64)f[6] < 0 ? 1 : 0;
                UInt64 mask = (UInt64)(-(Int64)neg);
                nint carry = neg;
                for (int k = 0; k < 7; k++) carry = (int)AddNoThrow(f[k] ^ mask, (UInt64)carry, out f[k]);
                int lz = 448;
                for (int k = 6; k >= 0; k--)
                    if (0u != f[k]) { lz = 64 * (6 - k) + (int)UInt64.LeadingZeroCount(f[k]); break; }
                /* No binary128 comes within 2^-124 of a multiple of pi/2, so the residual
                   keeps over 300 of its 448 bits (lz < 140); ten limbs leave the tail of
                   2/pi under 2^-462 of the units bit, so all 448 are meaningful. */
                uint word = (uint)lz / 64, wbits = (uint)lz % 64;
                InlineArray7<UInt64> s = default;
                for (uint k = word; k < 7; k++) {
                    UInt64 c = (wbits == 0 || k == word) ? 0 : f[(int)(k - word - 1)] >> (64 - (int)wbits);
                    s[(int)k] = (f[(int)(k - word)] << (int)wbits) | c;
                }
                U384 g = default;
                g[0] = (UInt128)s[1] | (UInt128)s[2] << 64;
                g[1] = (UInt128)s[3] | (UInt128)s[4] << 64;
                g[2] = (UInt128)s[5] | (UInt128)s[6] << 64;
                U384 pio2 = default;
                pio2[0] = PIO2_384[0];
                pio2[1] = PIO2_384[1];
                pio2[2] = PIO2_384[2];
                U384 tt = MultiplyHighUnsignedApproximate(g, pio2);
                int lzt = LeadingZeroCount(tt[2]);
                n = nn;
                negative = neg;
                t = ShiftLeftCore(tt, lzt);
                et = 1 - (lz + lzt);
            }
        }

        /* sum_{k>=0} (-1)^k coef[k]*u^k, eighteen terms by Horner in three tiers:
           terms 11..17 at 128 bits, 2..10 at 256, 0..1 at 384.  Every step stays
           positive because u*coef[k+1] < coef[k].  Each tier's slack -- under 2^-126
           for the narrow one, 2^-253 for the middle -- rides u^11 < 2^-161 or
           u^2 < 2^-29 (u < 2^-14.68) into the sum, so the result is within 2^-282 of
           the exact value, and the caller's multiply by u puts that below 2^-296.
           Mirrors correction_384 in metallic-rs's atan2.rs. */
        static U384 alternating(U384 u, UnsafeUInt128Accessor2D<UIntPtr3T> coef) {
            unchecked {
                UInt128 narrow = coef[17, 2];
                for (int k = 16; k >= 11; k--)
                    narrow = coef[k.ToUnsignedUnchecked(), 2] - MultiplyHighApproximate(u[2], narrow);
                U256 middle = default;
                middle[0] = 0;
                middle[1] = narrow;
                U256 u2 = default;
                u2[0] = u[1];
                u2[1] = u[2];
                for (int k = 10; k >= 2; k--) {
                    U256 c = default;
                    c[0] = coef[k.ToUnsignedUnchecked(), 1];
                    c[1] = coef[k.ToUnsignedUnchecked(), 2];
                    middle = SubtractUnchecked(c, MultiplyHighUnsignedApproximate(u2, middle));
                }
                U384 q = default;
                q[0] = 0;
                q[1] = middle[0];
                q[2] = middle[1];
                for (int k = 1; k >= 0; k--) {
                    U384 c = default;
                    c[0] = coef[k.ToUnsignedUnchecked(), 0];
                    c[1] = coef[k.ToUnsignedUnchecked(), 1];
                    c[2] = coef[k.ToUnsignedUnchecked(), 2];
                    q = SubtractUnchecked(c, MultiplyHighUnsignedApproximate(u, q));
                }
                return q;
            }
        }

        /* Round a normalized 384-bit fraction frac*2^(e2-384) to binary128 in the
           current mode.  The result is never subnormal here (see round_fast). */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static UInt128 round_384(U384 frac, int e2, UInt128 sign, MidpointRounding rm) {
            unchecked {
                UInt128 mantissa = frac[2] >> GUARD;
                int round_bit = (int)(frac[2] >> (GUARD - 1)) & 1;
                int sticky = ((frac[2] & (GUARD_MASK >> 1)) | frac[1] | frac[0]) != 0 ? 1 : 0;
                int up = ((IsNearest(rm) ? 0 != round_bit && ((0 != sticky) || (0 != (mantissa & 1)))
                                          : 0 != round_away(rm, sign) && ((0 != round_bit) || (0 != sticky))) ? 1 : 0);
                return sign | (((UInt128)(e2 + 16382) << 112) + (mantissa - IMPLICIT_BIT) + (uint)up);
            }
        }

        // the 384-bit path: everything the fast path would not decide
        [MethodImpl(MethodImplOptions.NoInlining | MethodImplOptions.AggressiveOptimization)]
        static UInt128 accurate(UInt128 m, int e, nint/*bool*/ cosine, UInt128 sign, MidpointRounding rm) {
            unchecked {
                int n, et;
                nint negative;
                U384 t = default;
                if (e < DIRECT) {
                    n = 0;
                    negative = 0;
                    t[0] = 0;
                    t[1] = 0;
                    t[2] = m << 15;
                    et = e + 1;
                } else
                    reduce_wide(m, e, out n, out negative, out t, out et);
                U384 u = ShiftRightUnsignedFull(MultiplyHighUnsignedApproximate(t, t), -2 * et);
                int k = (n >> 7) + (int)cosine, want_cos = k & 1, j = n & 127;
                sign ^= 0 != (k & 2) ? SIGN_MASK : 0;

                // sin(theta) = theta*(1 - u*Q) keeps theta's floating form, at most one bit short
                U384 s = SubtractUnchecked(t, MultiplyHighUnsignedApproximate(t, MultiplyHighUnsignedApproximate(u, alternating(u, SIN_COEF))));
                int lzs = LeadingZeroCount(s);
                s = ShiftLeftCore(s, lzs);
                int es = et - lzs;
                if (j == 0 && 0 == want_cos) {
                    return round_384(s, es, sign ^ (0 != negative ? SIGN_MASK : 0), rm);
                }
                // 1 - cos(theta) = u*Q, so T*cos(theta) = T - T*(u*Q) never overflows the frame
                U384 c = MultiplyHighUnsignedApproximate(u, alternating(u, COS_COEF));
                U384 first = default;
                first[0] = SINCOS[(uint)j, (uint)want_cos][0];
                first[1] = SINCOS[(uint)j, (uint)want_cos][1];
                first[2] = SINCOS[(uint)j, (uint)want_cos][2];
                U384 second = default;
                second[0] = SINCOS[(uint)j, 1 ^ (uint)want_cos][0];
                second[1] = SINCOS[(uint)j, 1 ^ (uint)want_cos][1];
                second[2] = SINCOS[(uint)j, 1 ^ (uint)want_cos][2];
                U384 @base = SubtractUnchecked(first, MultiplyHighUnsignedApproximate(first, c));
                U384 term = ShiftRightUnsignedFull(MultiplyHighUnsignedApproximate(second, s), -es);
                U384 f = (negative != want_cos) ? SubtractUnchecked(@base, term) : AddUnchecked(@base, term);
                int lz = LeadingZeroCount(f);
                return round_384(ShiftLeftCore(f, lz), -lz, sign, rm);
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]

        static UInt128 trig(UInt128 x, nint/*bool*/ cosine, MidpointRounding rm) {
            Debug.Assert(cosine == 0 || cosine == 1);
            UInt128 bits = x, ax = bits & ~SIGN_MASK, res;
            if (Misc.Unlikely(ax >= EXP_MASK)) { // Inf or NaN
                if (ax == EXP_MASK) { // +-Inf: domain error
                    RaiseExceptionFlagsDummy(FloatingPointExceptionFlags.Invalid);
                    // return EXP_MASK | QUIET_BIT;
                    return EXP_MASK | QUIET_BIT | (SIGN_MASK & bits);
                }

                if (0 == (ax & QUIET_BIT)) { // signaling NaN
                    RaiseExceptionFlagsDummy(FloatingPointExceptionFlags.Invalid);
                }
                // return bits | QUIET_BIT;
                // We do not change NaN.
                return bits;
            }
            if (Misc.Unlikely(ax < TINY)) {
                if (ax == 0) return 0 != cosine ? ONE : x; // exact
                                                           // sin(x) sits below x in magnitude and cos(x) below 1
                if (0 != cosine) {
                    res = ONE - (!IsNearest(rm) && (0 == round_away(rm, 0)) ? 1u : 0u);
                } else {
                    res = ax - (!IsNearest(rm) && (0 == round_away(rm, bits & SIGN_MASK)) ? 1u : 0u);
                    if (res < IMPLICIT_BIT) { // subnormal or zero after rounding
                        RaiseExceptionFlagsDummy(FloatingPointExceptionFlags.Underflow);
                    }
                    res |= bits & SIGN_MASK;
                }
                RaiseExceptionFlagsDummy(FloatingPointExceptionFlags.Inexact);
                return res;
            }
            UInt128 m = (ax & MANTISSA_MASK) | IMPLICIT_BIT, sign = (0 != cosine ? 0 : bits & SIGN_MASK);
            int e = (int)(ax >> 112) - BIAS;
            UInt128 frac, flip;
            int e2;
            if (!((0 != fast(m, e, cosine, out frac, out e2, out flip)) && (0 != round_fast(frac, e2, sign ^ flip, rm, out res))))
                res = accurate(m, e, cosine, sign, rm);
            RaiseExceptionFlagsDummy(FloatingPointExceptionFlags.Inexact);
            return res;
        }

        /* Combine the reduced angle with one row of the SINCOS table to produce
    the sine (Q = n>>7) or the cosine (Q = (n>>7)+1) in the fast path's
    floating frame frac*2^(e2-128), together with its sign bit *flip. */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static void combine_fast(int Q, int j, nint/*bool*/ negative, int et, UInt128 s1, UInt128 c1,
                                 out UInt128 frac, out int e2, out UInt128 flip) {
            unchecked {
                int want_cos = Q & 1;
                UInt128 flip_ = (0 != (Q & 2)) ? SIGN_MASK : 0;
                if (j == 0 && 0 == want_cos) {
                    /* SINCOS[0, 0] is zero, so the row degenerates to the residual's
                       own sine: sin(k*pi/2 + theta) = +-sin(theta). */
                    int lz = LeadingZeroCount(s1);
                    flip_ ^= (0 != negative) ? SIGN_MASK : 0;
                    flip = flip_;
                    frac = s1 << lz;
                    e2 = et - lz;
                    return;
                }
                {
                    UnsafeUInt128Accessor first = SINCOS[(uint)j, (uint)want_cos];
                    UnsafeUInt128Accessor second = SINCOS[(uint)j, (uint)(1 ^ want_cos)];
                    U256 @base = default;
                    @base[0] = first[1];
                    @base[1] = first[2];
                    U256 c = BigShiftLeft(MultiplyHighApproximate(first[2], c1), 2 * et + 128);
                    U256 s = BigShiftLeft(MultiplyHighApproximate(second[2], s1), et + 128);
                    U256 f = AddOrSubtractUnchecked(SubtractUnchecked(@base, c), s, negative != want_cos ? 1 : 0);
                    int lz = LeadingZeroCount(f[1]);
                    flip = flip_;
                    frac = ShiftLeftHighPartial(f, lz);
                    e2 = -lz;
                }
            }
        }

        /* The fast path for both sine and cosine: two frames ready to round,
           or 0 when the reduction cannot vouch for them.  The reduce / squares /
           sin_frac / cos_corr work is shared between the two outputs. */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static int fast_sincos(UInt128 m, int e,
                               out UInt128 s_frac, out int s_e2, out UInt128 s_flip,
                               out UInt128 c_frac, out int c_e2, out UInt128 c_flip) {
            unchecked {
                UInt128 u, v, u1;
                if (e < DIRECT) {
                    UInt128 t1 = m << 15;
                    int et = e + 1;
                    squares(t1, et, out u, out v, out u1);
                    UInt128 s1 = sin_frac(t1, u, v);
                    int lz = LeadingZeroCount(s1);
                    s_frac = s1 << lz;
                    s_e2 = et - lz;
                    s_flip = 0;
                    U256 all = default;
                    all[0] = ~(UInt128)0;
                    all[1] = ~(UInt128)0;
                    c_frac = SubtractUnchecked(all, BigShiftLeft(cos_corr(u1, u, v), 2 * et + 128))[1];
                    c_e2 = 0;
                    c_flip = 0;
                    return 1;
                }
                {
                    residual r;
                    if (0 == reduce(m, e, out r)) {
                        s_frac = default; s_e2 = 0; s_flip = default;
                        c_frac = default; c_e2 = 0; c_flip = default;
                        return 0;
                    }
                    squares(r.t1, r.et, out u, out v, out u1);
                    UInt128 s1 = sin_frac(r.t1, u, v);
                    UInt128 c1 = cos_corr(u1, u, v);
                    int Q = r.n >> 7, j = r.n & 127;
                    combine_fast(Q, j, r.negative, r.et, s1, c1, out s_frac, out s_e2, out s_flip);
                    combine_fast((Q + 1) & 3, j, r.negative, r.et, s1, c1, out c_frac, out c_e2, out c_flip);
                    return 1;
                }
            }
        }

        /* Combine the 384-bit reduced argument with one SINCOS row to round a
           single sine (cosine = 0) or cosine (cosine = 1).  s_norm is the
           normalized 384-bit sine of theta at exponent es; c is 1 - cos(theta)
           as produced by alternating(u, COS_COEF). */
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static UInt128 accurate_combine(int n, nint/*bool*/ negative,
                                        U384 s_norm, int es, U384 c,
                                        nint/*bool*/ cosine, UInt128 sign, MidpointRounding rm) {
            unchecked {
                int k = (n >> 7) + (int)cosine, want_cos = k & 1, j = n & 127;
                sign ^= (0 != (k & 2)) ? SIGN_MASK : 0;
                if (j == 0 && 0 == want_cos) {
                    return round_384(s_norm, es, sign ^ ((0 != negative) ? SIGN_MASK : 0), rm);
                }
                U384 first = default;
                {
                    UnsafeUInt128Accessor row = SINCOS[(uint)j, (uint)want_cos];
                    first[0] = row[0];
                    first[1] = row[1];
                    first[2] = row[2];
                }
                U384 second = default;
                {
                    UnsafeUInt128Accessor row = SINCOS[(uint)j, (uint)(1 ^ want_cos)];
                    second[0] = row[0];
                    second[1] = row[1];
                    second[2] = row[2];
                }
                U384 @base = SubtractUnchecked(first, MultiplyHighUnsignedApproximate(first, c));
                U384 term = ShiftRightUnsignedFull(MultiplyHighUnsignedApproximate(second, s_norm), -es);
                U384 f = (negative != want_cos) ? SubtractUnchecked(@base, term) : AddUnchecked(@base, term);
                int lz = LeadingZeroCount(f);
                return round_384(ShiftLeftCore(f, lz), -lz, sign, rm);
            }
        }

        // the 384-bit path for SinCos: everything the fast path would not decide,
        // for both outputs at once.
        [MethodImpl(MethodImplOptions.NoInlining | MethodImplOptions.AggressiveOptimization)]
        static (UInt128 s, UInt128 c) accurate_sincos(UInt128 m, int e, UInt128 sign, MidpointRounding rm) {
            unchecked {
                int n, et;
                nint/*bool*/ negative;
                U384 t = default;
                if (e < DIRECT) {
                    n = 0;
                    negative = 0;
                    t[0] = 0;
                    t[1] = 0;
                    t[2] = m << 15;
                    et = e + 1;
                } else
                    reduce_wide(m, e, out n, out negative, out t, out et);
                U384 u = ShiftRightUnsignedFull(MultiplyHighUnsignedApproximate(t, t), -2 * et);
                U384 s_norm = SubtractUnchecked(t, MultiplyHighUnsignedApproximate(t, MultiplyHighUnsignedApproximate(u, alternating(u, SIN_COEF))));
                int lzs = LeadingZeroCount(s_norm);
                s_norm = ShiftLeftCore(s_norm, lzs);
                int es = et - lzs;
                U384 c = MultiplyHighUnsignedApproximate(u, alternating(u, COS_COEF));
                UInt128 s_res = accurate_combine(n, negative, s_norm, es, c, 0, sign, rm);
                UInt128 c_res = accurate_combine(n, negative, s_norm, es, c, 1, sign, rm);
                return (s_res, c_res);
            }
        }

        // SinCos for a binary128 bit pattern.  The cosine is even, so the input
        // sign never reaches it directly: cos(x) = sin(x + pi/2) shows up as a
        // quadrant advance inside combine_fast / accurate_combine.
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        static (UInt128 s, UInt128 c) trig(UInt128 x, MidpointRounding rm) {
            unchecked {
                UInt128 bits = x, ax = bits & ~SIGN_MASK;
                if (Misc.Unlikely(ax >= EXP_MASK)) { // Inf or NaN
                    if (ax == EXP_MASK) { // +-Inf: domain error for both
                        RaiseExceptionFlagsDummy(FloatingPointExceptionFlags.Invalid);
                        UInt128 nan = EXP_MASK | QUIET_BIT | (SIGN_MASK & bits);
                        return (nan, nan);
                    }
                    if (0 == (ax & QUIET_BIT)) { // signaling NaN
                        RaiseExceptionFlagsDummy(FloatingPointExceptionFlags.Invalid);
                    }
                    return (bits, bits);
                }
                if (Misc.Unlikely(ax < TINY)) {
                    UInt128 s_res, c_res;
                    if (ax == 0) {
                        s_res = x;    // sin(+-0) = +-0
                        c_res = ONE;  // cos(+-0) = 1
                    } else {
                        // sin(x) sits below x in magnitude
                        s_res = ax - (!IsNearest(rm) && (0 == round_away(rm, bits & SIGN_MASK)) ? 1u : 0u);
                        if (s_res < IMPLICIT_BIT) { // subnormal or zero after rounding
                            RaiseExceptionFlagsDummy(FloatingPointExceptionFlags.Underflow);
                        }
                        s_res |= bits & SIGN_MASK;
                        // cos(x) sits below 1
                        c_res = ONE - (!IsNearest(rm) && (0 == round_away(rm, 0)) ? 1u : 0u);
                    }
                    RaiseExceptionFlagsDummy(FloatingPointExceptionFlags.Inexact);
                    return (s_res, c_res);
                }
                {
                    UInt128 m = (ax & MANTISSA_MASK) | IMPLICIT_BIT, sign = bits & SIGN_MASK;
                    int e = (int)(ax >> 112) - BIAS;
                    UInt128 s_frac, s_flip, c_frac, c_flip, s_res = default, c_res = default;
                    int s_e2, c_e2;
                    int ok = fast_sincos(m, e, out s_frac, out s_e2, out s_flip,
                                                  out c_frac, out c_e2, out c_flip);
                    if (0 != ok) ok = round_fast(s_frac, s_e2, sign ^ s_flip, rm, out s_res);
                    if (0 != ok) ok = round_fast(c_frac, c_e2, c_flip, rm, out c_res);
                    if (0 == ok) {
                        (s_res, c_res) = accurate_sincos(m, e, sign, rm);
                    }
                    RaiseExceptionFlagsDummy(FloatingPointExceptionFlags.Inexact);
                    return (s_res, c_res);
                }
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static UInt64 Sin(UInt64 lo, UInt64 hi, out UInt64 result_hi) {
            unchecked {
                UInt128 r = trig(((UInt128)hi << 64) | lo, 0, MidpointRounding.ToEven);
                result_hi = (UInt64)(r >> 64);
                return (UInt64)r;
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static UInt64 Sin(UInt64 lo, UInt64 hi, MidpointRounding mode, out UInt64 result_hi) {
            unchecked {
                UInt128 r = trig(((UInt128)hi << 64) | lo, 0, mode);
                result_hi = (UInt64)(r >> 64);
                return (UInt64)r;
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static UInt128 Sin(UInt128 bits) {
            return trig(bits, 0, MidpointRounding.ToEven);
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static UInt128 Sin(UInt128 bits, MidpointRounding mode) {
            return trig(bits, 0, mode);
        }


        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static UInt64 Cos(UInt64 lo, UInt64 hi, out UInt64 result_hi) {
            unchecked {
                UInt128 r = trig(((UInt128)hi << 64) | lo, 1, MidpointRounding.ToEven);
                result_hi = (UInt64)(r >> 64);
                return (UInt64)r;
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static UInt64 Cos(UInt64 lo, UInt64 hi, MidpointRounding mode, out UInt64 result_hi) {
            unchecked {
                UInt128 r = trig(((UInt128)hi << 64) | lo, 1, mode);
                result_hi = (UInt64)(r >> 64);
                return (UInt64)r;
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static UInt128 Cos(UInt128 bits) {
            return trig(bits, 1, MidpointRounding.ToEven);
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static UInt128 Cos(UInt128 bits, MidpointRounding mode) {
            return trig(bits, 1, mode);
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static void SinCos(out UInt64 sin_lo, out UInt64 sin_hi,
                          out UInt64 cos_lo, out UInt64 cos_hi,
                          UInt64 lo, UInt64 hi) {
            unchecked {
                UInt128 x = ((UInt128)hi << 64) | lo;
                var (s, c) = trig(x, MidpointRounding.ToEven);
                sin_lo = (UInt64)s;
                sin_hi = (UInt64)(s >> 64);
                cos_lo = (UInt64)c;
                cos_hi = (UInt64)(c >> 64);
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static void SinCos(out UInt64 sin_lo, out UInt64 sin_hi,
                                  out UInt64 cos_lo, out UInt64 cos_hi,
                                  UInt64 lo, UInt64 hi, MidpointRounding mode) {
            unchecked {
                UInt128 x = ((UInt128)hi << 64) | lo;
                var (s, c) = trig(x, mode);
                sin_lo = (UInt64)s;
                sin_hi = (UInt64)(s >> 64);
                cos_lo = (UInt64)c;
                cos_hi = (UInt64)(c >> 64);
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static (UInt128 Sin, UInt128 Cos) SinCos(
            UInt128 bits)
            => trig(bits, MidpointRounding.ToEven);

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static (UInt128 Sin, UInt128 Cos) SinCos(
             UInt128 bits, MidpointRounding mode) {
            return trig(bits, mode);
        }
